# Generate the small HEALPix fixtures hpxproj.sh uses, from
# fits/wmap_ring.fits (nside 256, RING, no COORDSYS).
#
# usage (from Tests/): python hpxproj/make_fixtures.py
#
# Writes fits/hpxproj/:
#   ring64_{gal,equ,ecl,unk}.fits  full-sky RING nside 64, binary table,
#                                  COORDSYS G / C / E / absent
#   nested64_gal.fits              full-sky NESTED nside 64, binary table
#   ascii32_gal.fits               full-sky RING nside 32, ASCII table
#
# The maps are wmap_ring degraded with healpy.ud_grade (block average),
# so the values are floats. The sky system is only a label here (the
# same pixel values in every variant); what matters is that ds9 keeps
# it through the resampling.
# Needs numpy, astropy, healpy.

import os

import numpy as np
import healpy as hp
from astropy.io import fits

SRC = 'fits/wmap_ring.fits'
OUT = 'fits/hpxproj'


def header(nside, ordering, coordsys):
    hd = fits.Header()
    hd['PIXTYPE'] = ('HEALPIX', 'HEALPIX pixelisation')
    hd['ORDERING'] = (ordering, 'Pixel ordering scheme, either RING or NESTED')
    hd['NSIDE'] = (nside, 'Resolution parameter for HEALPIX')
    hd['FIRSTPIX'] = (0, 'First pixel # (0 based)')
    hd['LASTPIX'] = (12 * nside * nside - 1, 'Last pixel # (0 based)')
    hd['INDXSCHM'] = ('IMPLICIT', 'Indexing: IMPLICIT or EXPLICIT')
    if coordsys:
        hd['COORDSYS'] = (coordsys, 'Ecliptic, Galactic or Celestial (equatorial)')
    hd['OBJECT'] = ('wmap_ring ud_grade', 'Generated by hpxproj/make_fixtures.py')
    return hd


def write_bin(path, m, nside, ordering, coordsys):
    col = fits.Column(name='SIGNAL', format='E', array=m.astype(np.float32))
    hdu = fits.BinTableHDU.from_columns([col], header=header(nside, ordering, coordsys))
    hdu.writeto(path, overwrite=True)
    print(f'wrote {path}')


def write_ascii(path, m, nside, ordering, coordsys):
    col = fits.Column(name='SIGNAL', format='E15.7', array=m.astype(np.float32))
    hdu = fits.TableHDU.from_columns([col], header=header(nside, ordering, coordsys))
    hdu.writeto(path, overwrite=True)
    print(f'wrote {path}')


def main():
    os.makedirs(OUT, exist_ok=True)
    full = hp.read_map(SRC, field=0, nest=False, dtype=np.float64)

    ring64 = hp.ud_grade(full, 64, order_in='RING', order_out='RING')
    for tag, cs in (('gal', 'G'), ('equ', 'C'), ('ecl', 'E'), ('unk', None)):
        write_bin(f'{OUT}/ring64_{tag}.fits', ring64, 64, 'RING', cs)

    nested64 = hp.reorder(ring64, r2n=True)
    write_bin(f'{OUT}/nested64_gal.fits', nested64, 64, 'NESTED', 'G')

    ring32 = hp.ud_grade(full, 32, order_in='RING', order_out='RING')
    write_ascii(f'{OUT}/ascii32_gal.fits', ring32, 32, 'RING', 'G')


if __name__ == '__main__':
    main()
